function ExampleBlock({ example }: { example: Example }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="rounded-xl border border-ink-700 bg-ink-900/40 p-3">
      <div className="mb-2 flex items-center justify-between gap-2">
        <div className="text-sm font-medium">{example.title}</div>
        <button
          type="button"
          className="rounded px-2 py-1 text-[11px] text-neutral-400 hover:bg-ink-700 hover:text-neutral-100"
          onClick={() => {
            void navigator.clipboard?.writeText(example.prompt).then(() => {
              setCopied(true);
              window.setTimeout(() => setCopied(false), 1200);
            });
          }}
        >
          {copied ? "Скопировано" : "Копировать"}
        </button>
      </div>
      <pre className="whitespace-pre-wrap rounded-lg bg-ink-800 px-3 py-2 text-xs leading-5 text-neutral-200">{example.prompt}</pre>
      <p className="mt-2 text-xs text-neutral-500">{example.why}</p>
    </div>
  );
}

export function DomainGuide() {
  const [slug, setSlug] = useState(GUIDES[0].slug);
  const guide = GUIDES.find((item) => item.slug === slug) || GUIDES[0];
  const domain = DOMAINS.find((item) => item.slug === guide.slug);

  return (
    <div className="max-w-3xl">
      <h1 className="text-xl font-semibold">Справка по доменам</h1>
      <p className="mb-5 text-sm text-neutral-500">
        Короткая задача с границей и примером результата работает лучше длинного «сделай хорошо».
      </p>
      <div className="mb-5 flex flex-wrap gap-1" role="tablist" aria-label="Домены">
        {GUIDES.map((item) => {
          const meta = DOMAINS.find((domain) => domain.slug === item.slug);
          const active = item.slug === guide.slug;
          return (
            <button
              key={item.slug}
              type="button"
              role="tab"
              aria-selected={active}
              onClick={() => setSlug(item.slug)}
              className={`rounded px-3 py-1.5 text-xs ${active ? "bg-accent-600 text-white" : "bg-ink-800 text-neutral-400"}`}
            >
              {meta?.label || item.slug}
            </button>
          );
        })}
      </div>
      <section className="mb-6">
        <h2 className="mb-1 text-sm font-semibold" style={{ color: domain?.color }}>{domain?.label}</h2>
        <p className="text-sm text-neutral-300">{guide.start}</p>
      </section>
      <section className="mb-6">
        <h2 className="mb-2 text-sm font-semibold">Как ставить задачу</h2>
        <ul className="list-disc space-y-1 pl-5 text-sm text-neutral-300">
          {guide.rules.map((rule) => <li key={rule}>{rule}</li>)}
        </ul>
      </section>
      <section className="mb-6 space-y-3">
        <h2 className="text-sm font-semibold">Примеры</h2>
        {guide.examples.map((example) => <ExampleBlock key={example.title} example={example} />)}
      </section>
      <section>
        <h2 className="mb-2 text-sm font-semibold">Так задача разъезжается</h2>
        <ul className="list-disc space-y-1 pl-5 text-sm text-neutral-400">
          {guide.avoid.map((item) => <li key={item}>{item}</li>)}
        </ul>
      </section>
    </div>
  );
}
